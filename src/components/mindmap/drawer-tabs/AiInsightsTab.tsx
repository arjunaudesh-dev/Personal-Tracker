'use client';

import { BrainCircuit, Loader2, Plus, Sparkles } from 'lucide-react';
import { useState } from 'react';

import type { MindMapTaskNode } from '@/lib/types/mindmap';
import { useNexus } from '@/store/nexus-store';
import { uid } from '@/lib/parser/utils';

/** Tab 1b — cached Gemini bottleneck analysis + subtask generator. */
export function AiInsightsTab({ task }: { task: MindMapTaskNode }) {
  const { state, dispatch } = useNexus();
  const [loading, setLoading] = useState(false);
  const [subtasks, setSubtasks] = useState<string[]>([]);
  const [source, setSource] = useState<string>('');
  const [error, setError] = useState<string>('');

  const generate = async () => {
    setLoading(true);
    setError('');
    try {
      const res = await fetch('/api/ai', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          task: 'subtask-draft',
          payload: { title: task.title, notes: task.markdownNotes, group: task.groupCategory },
        }),
      });
      const json = await res.json();
      if (!res.ok) throw new Error(json.error ?? 'AI request failed');
      setSubtasks(json.data?.subtasks ?? []);
      setSource(json.source ?? 'local');
    } catch (err) {
      setError(err instanceof Error ? err.message : 'AI request failed');
    } finally {
      setLoading(false);
    }
  };

  const promote = (label: string) => {
    dispatch({
      type: 'add-task',
      task: {
        id: uid('task'),
        parentId: task.id,
        boardId: task.boardId,
        title: label,
        markdownNotes: 'Generated by the NEXUS subtask generator.',
        groupCategory: task.groupCategory,
        direction: task.direction,
        depth: task.depth + 1,
        posX: 0,
        posY: 0,
        status: 'todo',
        priority: task.priority,
        tags: ['ai-generated'],
        isCollapsed: false,
        progress: 0,
        isAutoCalculated: false,
        cashflow: null,
        reminders: [],
        attachments: [],
        contacts: [],
        aiInsight: null,
        dueDate: task.dueDate,
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      },
    });
    setSubtasks((prev) => prev.filter((s) => s !== label));
  };

  const insight = task.aiInsight;

  return (
    <div className="space-y-4">
      {insight ? (
        <section className="rounded-xl border border-nexus-violet/25 bg-nexus-violet/[0.07] p-3">
          <p className="text-[11px] leading-relaxed text-slate-300">{insight.summary}</p>
          <ul className="mt-2 space-y-1">
            {insight.directives.map((d, i) => (
              <li key={i} className="flex gap-2 text-[10.5px] text-slate-400">
                <span className="text-nexus-violet">▸</span>
                {d}
              </li>
            ))}
          </ul>
          <p className="mt-2 font-mono text-[9px] text-slate-600">
            generated {new Date(insight.generatedAt).toLocaleString()} · confidence{' '}
            {Math.round(insight.confidence * 100)}%
          </p>
        </section>
      ) : null}

      <section className="glass-soft p-3">
        <div className="flex items-center gap-1.5">
          <BrainCircuit className="h-3.5 w-3.5 text-nexus-violet" />
          <p className="text-[10px] font-semibold uppercase tracking-wider text-nexus-violet">
            Subtask generator
          </p>
        </div>
        <p className="mt-1.5 text-[11px] leading-relaxed text-slate-400">
          Expands “{task.title}” into sequenced site subtasks using the Gemini fast model with a
          deterministic offline fallback.
        </p>
        <button onClick={generate} disabled={loading} className="btn btn-violet mt-2.5">
          {loading ? <Loader2 className="h-3 w-3 animate-spin" /> : <Sparkles className="h-3 w-3" />}
          {loading ? 'Generating…' : 'Generate breakdown'}
        </button>
        {error ? <p className="mt-2 text-[10px] text-nexus-rose">{error}</p> : null}
        {source ? (
          <p className="mt-2 font-mono text-[9px] text-slate-600">engine: {source}</p>
        ) : null}
      </section>

      {subtasks.length > 0 ? (
        <section>
          <p className="label-caps mb-2">Proposed subtasks ({subtasks.length})</p>
          <ul className="space-y-1">
            {subtasks.map((s) => (
              <li
                key={s}
                className="flex items-center gap-2 rounded-xl border border-white/[0.07] bg-white/[0.02] px-3 py-2"
              >
                <span className="min-w-0 flex-1 text-[11px] text-slate-300">{s}</span>
                <button onClick={() => promote(s)} className="btn h-7 gap-1 px-2 text-[10px]">
                  <Plus className="h-3 w-3" />
                  Promote
                </button>
              </li>
            ))}
          </ul>
        </section>
      ) : null}

      <section className="rounded-xl border border-white/[0.07] bg-white/[0.02] p-3">
        <p className="label-caps mb-1.5">Linked context</p>
        <p className="text-[10.5px] leading-relaxed text-slate-500">
          {state.links.filter((l) => l.sourceTaskId === task.id || l.targetTaskId === task.id).length}{' '}
          cross-system links ·{' '}
          {
            state.transactions.filter((t) => t.linkedTaskId === task.id).length
          }{' '}
          ledger entries · {task.contacts.length} contacts · {task.attachments.length} documents
        </p>
      </section>
    </div>
  );
}
