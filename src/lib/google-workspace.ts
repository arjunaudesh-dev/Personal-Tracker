import { TaskReminder } from '@/types/mindmap';

export function createGoogleCalendarUrl(
  title: string,
  details: string,
  dateStr: string,
  timeStr = '09:00'
): string {
  const cleanDate = dateStr.replace(/[^0-9]/g, '');
  const cleanTime = timeStr.replace(/[^0-9]/g, '').padEnd(4, '0') + '00';
  const startIso = `${cleanDate}T${cleanTime}`;
  
  const params = new URLSearchParams({
    action: 'TEMPLATE',
    text: `[NEXUS] ${title}`,
    details: `${details}\n\nGenerated by NEXUS LIFE-OS Command Center`,
    dates: `${startIso}/${startIso}`,
  });

  return `https://calendar.google.com/calendar/render?${params.toString()}`;
}

export function syncAlarmToGoogleTasks(reminder: TaskReminder): boolean {
  if (typeof window !== 'undefined') {
    const existing = JSON.parse(localStorage.getItem('nexus_gcal_synced_alarms') || '[]');
    existing.push({ ...reminder, syncedAt: new Date().toISOString() });
    localStorage.setItem('nexus_gcal_synced_alarms', JSON.stringify(existing));
    return true;
  }
  return false;
}
